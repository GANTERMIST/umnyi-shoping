def build(segs: list[Seg], intent: str, kind: str, platform: str) -> dict:
    text, tags = [], []
    for s, slot in segs:
        if not s:
            continue
        toks = [t for t, _, _ in tokenize(s)]
        for i, t in enumerate(toks):
            text.append(t)
            tags.append("O" if not slot else ("B-" if i == 0 else "I-") + slot)
    return {"tokens": text, "tags": tags, "intent": intent, "kind": kind, "platform": platform}


def typo(word: str, rng: random.Random) -> str:
    if len(word) < 5 or not word.isalpha():
        return word
    i = rng.randrange(1, len(word) - 1)
    op = rng.random()
    if op < 0.4:
        return word[:i] + word[i + 1:]                       # пропуск буквы
    if op < 0.8:
        return word[:i - 1] + word[i] + word[i - 1] + word[i + 1:]  # перестановка
    return word[:i] + word[i] + word[i:]                     # удвоение


class Gen:
    def __init__(self, games: list[str], seed: int):
        self.rng = random.Random(seed)
        self.games = games
        self.aliases = list(ALIASES)

    def r(self, xs):
        return self.rng.choice(xs)

    def game(self) -> Seg:
        g = self.r(self.games) if self.rng.random() < 0.75 else self.r(self.aliases)
        if self.rng.random() < 0.08:  # иногда пользователь пишет кусок названия
            parts = g.split()
            g = " ".join(parts[:max(1, len(parts) - 1)])
        words = g.split()
        if self.rng.random() < 0.12:
            j = self.rng.randrange(len(words))
            words[j] = typo(words[j].lower(), self.rng)
        return " ".join(words), "GAME"

    def price(self) -> list[Seg]:
        v = self.r(PRICE_VALUES)
        rng = self.rng.random()
        pre = (self.r(PRICE_PRE), None)
        if v in WORD_PRICES and rng < 0.15:
            return [pre, (self.r(WORD_PRICES[v]), "PRICE")] + ([(self.r(["рублей", "руб"]), None)] if self.rng.random() < 0.3 else [])
        if v >= 1000 and v % 500 == 0 and rng < 0.35:
            k = f"{v / 1000:g}"
            num = self.r([f"{k}к", f"{k} к", f"{k}k", f"{k} тыс", f"{k.replace('.', ',')}к"])
            return [pre, (num, "PRICE")] + ([(self.r(["рублей", "руб"]), None)] if self.rng.random() < 0.2 else [])
        if v >= 1000 and rng < 0.45:
            return [pre, (f"{v // 1000} {v % 1000:03d}", "PRICE"), (self.r(PRICE_POST), None)]
        if rng < 0.55:
            return [pre, (f"{v}р", "PRICE")]
        segs = [pre, (str(v), "PRICE"), (self.r(PRICE_POST), None)]
        if self.rng.random() < 0.12:  # «1500 максимум» без предлога
            segs = [(str(v), "PRICE"), (self.r(["максимум", "макс", "рублей максимум", "не больше", "руб бюджет"]), None)]
        return segs

    def plat(self) -> tuple[str, Seg]:
        p = self.r(list(PLAT_PHR))
        return p, (self.r(PLAT_PHR[p]), None)

    def topup_item(self) -> Seg:
        x = self.rng.random()
        if x < 0.35:
            return self.r(TOPUP_ITEMS), "GAME"
        cur, game = self.r(CURRENCY), self.r(CURRENCY_GAMES)
        if x < 0.75:
            return f"{cur} {self.r(['', '', 'для', 'в', 'на'])} {game}".replace("  ", " "), "GAME"
        return f"{game} {cur}", "GAME"

    def bare(self) -> dict:
        """Просто название игры (часто с цифрой: «hades 2», «gta 6») — значит, ищем, где купить."""
        segs: list[Seg] = [self.game()]
        if self.rng.random() < 0.2:
            segs.append((self.r(["цена", "цены", "стоимость", "сколько", "почем", "купить", "ключ", "дешево"]), None))
            if segs[-1][0] == "ключ":
                return build(segs, "buy", "ключ", "any")
        return build(segs, "buy", "any", "any")

    def followup(self) -> dict:
        """Уточнение в разговоре без названия игры: «а гифтом?», «а для xbox», «а до 1000?» — игра из прошлой реплики."""
        lead = (self.r(["а", "а", "а если", "и", "тогда", "а можно", "а есть", "а как насчет", "ну а", "а теперь", "лучше"]), None)
        x = self.rng.random()
        kind, platform = "any", "any"
        if x < 0.35:
            kind = self.r(["ключ", "гифт", "аккаунт", "магазин"])
            segs = [lead, (self.r(KIND_PHR[kind]), None)]
        elif x < 0.65:
            platform, ps = self.plat()
            segs = [lead, ps]
        elif x < 0.85:
            segs = [lead] + self.price()
        else:
            segs = [lead, (self.r(["подешевле", "дешевле есть", "еще варианты", "другие варианты", "что-то дешевле",
                                   "у надежного продавца", "без аккаунтов"]), None)]
        if self.rng.random() < 0.25:
            platform, ps = self.plat() if platform == "any" else (platform, ("", None))
            segs.append(ps)
        return build(segs, "buy", kind, platform)

    def buy(self) -> dict:
        topup = self.rng.random() < 0.14
        if topup:
            item: Seg = self.topup_item()
            kind = "пополнение"
        else:
            item = self.game()
            kind = self.r(["any", "any", "any", "ключ", "ключ", "гифт", "гифт", "аккаунт", "магазин", "пополнение"])
            if kind == "пополнение":
                kind = "any"
        parts: list[list[Seg]] = []
        platform = "any"
        if kind not in ("any", "пополнение") or (topup and self.rng.random() < 0.3):
            parts.append([(self.r(KIND_PHR[kind]), None)])
        if self.rng.random() < 0.45:
            platform, ps = self.plat()
            parts.append([ps])
        if self.rng.random() < 0.45:
            parts.append(self.price())
        self.rng.shuffle(parts)
        lead = (self.r(BUY_LEAD), None)
        if self.rng.random() < 0.25 and parts and parts[0][0][1] is None and len(parts[0]) == 1:
            segs = [lead] + parts[0] + [item] + [s for p in parts[1:] for s in p]  # «ключ elden ring для стима»
        else:
            segs = [lead, item] + [s for p in parts for s in p]
        segs.append((self.r(BUY_TAIL), None))
        if self.rng.random() < 0.06:
            segs.insert(0, (self.r(GREET_PREFIX), None))
        return build(segs, "buy", kind, platform)

    def recommend(self) -> dict:
        if self.rng.random() < 0.15:
            segs: list[Seg] = [(self.r(REC_FIXED), None)]
            if self.rng.random() < 0.4:
                segs += self.price()
            return build(segs, "recommend", "any", "any")
        if self.rng.random() < 0.12:
            return build([(self.r(REC_SIMILAR), None), self.game()], "recommend", "any", "any")
        if self.rng.random() < 0.12:  # «что посоветуешь из выживалок до 1500»
            segs = [(self.r(REC_FROM), None), (self.r(GENRE_GEN), "GENRE")]
            if self.rng.random() < 0.4:
                segs += self.price()
            return build(segs, "recommend", "any", "any")
        segs = [(self.r(REC_LEAD), None)]
        genre_first = self.rng.random() < 0.5
        g: Seg = (self.r(REC_GENRES), "GENRE")
        has_genre = self.rng.random() < 0.6
        if has_genre and genre_first:
            segs += [g, (self.r(["", "игру", "игры", ""]), None)]
        else:
            segs.append((self.r(REC_OBJ), None))
            if has_genre:
                segs += [(self.r(["в жанре", "жанра", "типа", "", ""]), None), g]
        platform = "any"
        extra: list[list[Seg]] = [[(self.r(REC_CTX), None)]]
        if self.rng.random() < 0.25:
            platform, ps = self.plat()
            extra.append([ps])
        if self.rng.random() < 0.45:
            extra.append(self.price())
        self.rng.shuffle(extra)
        segs += [s for e in extra for s in e]
        return build(segs, "recommend", "any", platform)

    def review(self) -> dict:
        t = self.r(REVIEW_T)
        pre, post = t.split("{g}")
        segs = [(pre, None), self.game(), (post, None)]
        platform = "any"
        if self.rng.random() < 0.1:
            platform, ps = self.plat()
            segs.append(ps)
        return build(segs, "review", "any", platform)

    def compare(self) -> dict:
        t = self.r(COMPARE_T)
        o, platform = self.r(OFFICIAL_PHR)
        pre, post = t.split("{g}")
        segs = []
        for chunk, slot in ((pre, None), ("{G}", "GAME"), (post, None)):
            if slot:
                segs.append(self.game())
            elif "{o}" in chunk:
                a, b = chunk.split("{o}")
                segs += [(a, None), (o, None), (b, None)]
            else:
                segs.append((chunk, None))
        if "{o}" not in t:
            platform = "any"
        return build(segs, "compare", "any", platform)

    def faq(self) -> dict:
        if self.rng.random() < 0.15:
            p = self.r(["Steam", "Xbox", "PlayStation", "Epic"])
            t = self.r(FAQ_PLAT)
            kind = FAQ_PLAT_KIND[FAQ_PLAT.index(t)]
            pre, post = t.split("{p}")
            return build([(pre, None), (self.r(PLAT_PHR[p]), None), (post, None)], "faq", kind, p)
        kind = self.r(list(FAQ_T))
        return build([(self.r(FAQ_T[kind]), None)], "faq", kind, "any")

    def greet(self) -> dict:
        segs = [(self.r(GREET), None)]
        if self.rng.random() < 0.15:
            segs.append((self.r(GREET), None))
        return build(segs, "greet", "any", "any")

    def other(self) -> dict:
        if self.rng.random() < 0.45:
            goods = self.r(OTHER_GOODS) if self.rng.random() < 0.6 else self.r(OTHER_BRANDS)
            segs: list[Seg] = [(self.r(OTHER_GOODS_LEAD), None), (f"{goods} {self.r(GOODS_SUFFIX)}", None),
                               (self.r(BUY_TAIL), None)]
            if self.rng.random() < 0.4:
                segs += self.price()
            return build(segs, "other", "any", "any")
        segs = [(self.r(OTHER), None)]
        if self.rng.random() < 0.1:
            segs.insert(0, (self.r(GREET_PREFIX), None))
        return build(segs, "other", "any", "any")


MIX = {"buy": 0.37, "bare": 0.04, "followup": 0.03, "recommend": 0.15, "review": 0.11, "compare": 0.09, "faq": 0.09,
       "greet": 0.05, "other": 0.10}


def generate(n: int, games: list[str], seed: int = 0) -> list[dict]:
    g = Gen(games, seed)
    rng = random.Random(seed + 1)
    kinds, weights = list(MIX), list(MIX.values())
    out = []
    while len(out) < n:
        ex = getattr(g, rng.choices(kinds, weights)[0])()
        if ex["tokens"]:
            out.append(ex)
    return out


def split_games(extra: list[str] = (), seed: int = 7, holdout: float = 0.15) -> tuple[list[str], list[str]]:
    """Названия для обучения и отложенные (модель их не видит) — для честной проверки на новых играх."""
    names = sorted({n.strip() for n in list(GAMES) + list(extra) if n.strip()})
    rng = random.Random(seed)
    rng.shuffle(names)
    k = int(len(names) * holdout)
    return names[k:], names[:k]
